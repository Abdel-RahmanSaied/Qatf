/** Arabic counted nouns change shape with the number: one, two, 3–10, 11+.
 * `forms` are [singular, dual, plural 3–10, singular accusative 11+]. The
 * digits stay Western, matching the tabular numbers used across the app. */
type Forms = readonly [string, string, string, string];
function count(n: number, [one, two, few, many]: Forms): string {
  const num = n.toLocaleString("en");
  if (n === 1) return `${one} ${one.endsWith("ة") ? "واحدة" : "واحد"}`;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return `${num} ${few}`;
  return `${num} ${many}`;
}

